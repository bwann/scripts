# Entry point
# ---------------------------------------------------------------------------


def main():  # pylint: disable=too-many-locals
    """Parse arguments and orchestrate the certificate deploy."""
    parser = argparse.ArgumentParser(
        description="Push a TLS certificate/key pair to a Ubiquiti EdgeSwitch via tftp",
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument(
        "--switch-host", required=True, help="Switch hostname or IP to ssh into"
    )
    parser.add_argument("--key-file", required=True, help="Private key file")
    parser.add_argument(
        "--cert-file", required=True, help="Leaf certificate file (no chain)"
    )
    parser.add_argument(
        "--ca-file", required=True, help="Intermediate chain file (no leaf)"
    )

    parser.add_argument(
        "--tftp-push-host",
        required=True,
        help="Host to scp the staged PEMs to (e.g. tftp-server.example.com)",
    )
    parser.add_argument(
        "--tftp-fetch-host",
        required=True,
        help="Hostname/address the switch itself uses in its 'copy tftp://' command"
        "(the switch may not be able to reach --tftp-push-host by the same name)",
    )
    parser.add_argument(
        "--tftp-dir", default=DEFAULT_TFTP_DIR, help="Staging dir on the tftp host"
    )
    parser.add_argument(
        "--tftp-url-path",
        default=DEFAULT_TFTP_URL_PATH,
        help="Directory the switch's 'copy tftp://' command uses, relative to the "
        "tftp server's root (not the same thing as --tftp-dir, which is an "
        "absolute filesystem path)",
    )
    parser.add_argument(
        "--ssh-key", default=DEFAULT_SSH_KEY, help="SSH key for the tftp host push"
    )
    parser.add_argument(
        "--push-user", default=DEFAULT_PUSH_USER, help="SSH user for the tftp host push"
    )
    parser.add_argument(
        "--work-dir",
        default=DEFAULT_WORK_DIR,
        help="Directory to build the staged PEMs under before scp (a fresh "
        "0700 subdirectory is created here per run and removed afterward)",
    )

    parser.add_argument("--username", default=None, help="Switch vty username")
    parser.add_argument("--password", default=None, help="Switch vty password")
    parser.add_argument(
        "--enable-password", default=None, help="Switch enable password"
    )
    parser.add_argument(
        "--creds-file",
        default=None,
        help=f"Local creds JSON file (default: {DEFAULT_CREDS_DIR}/<switch-host>.json)",
    )
    parser.add_argument(
        "--vault-path",
        default=None,
        help="Vault KV v2 path (default: VAULT_SWITCH_PATH/<switch-host>)",
    )

    parser.add_argument(
        "--keep-remote-files",
        action="store_true",
        help="Don't delete the staged PEMs from the tftp host after a "
        "successful deploy (debugging)",
    )
    parser.add_argument(
        "--quiet", action="store_true", help="Only print output on failure"
    )
    parser.add_argument(
        "--debug", action="store_true", help="Stream the raw switch CLI transcript"
    )
    args = parser.parse_args()

    for label, path in (
        ("--key-file", args.key_file),
        ("--cert-file", args.cert_file),
        ("--ca-file", args.ca_file),
    ):
        if not os.path.isfile(path):
            die(f"{label} '{path}' doesn't exist!")

    username, password, enable_password = resolve_credentials(args)
    push_target = PushTarget(
        args.ssh_key, args.push_user, args.tftp_push_host, args.tftp_dir
    )

    workdir = tempfile.mkdtemp(prefix="edgeswitch-cert-", dir=args.work_dir)
    try:
        (primary_path, primary_name), (chain_path, chain_name) = build_pem_files(
            args.cert_file, args.key_file, args.ca_file, workdir
        )

        if not args.quiet:
            print(
                f"Staging {primary_name}, {chain_name} on {args.tftp_push_host}:{args.tftp_dir} ..."
            )
        scp_upload([primary_path, chain_path], push_target, args.debug)
    finally:
        shutil.rmtree(workdir, ignore_errors=True)

    if not args.quiet:
        print(f"Deploying to {args.switch_host} ...")
    try:
        run_deploy_sequence(
            args.switch_host,
            username,
            password,
            enable_password,
            args.tftp_fetch_host,
            args.tftp_url_path,
            primary_name,
            chain_name,
            args.debug,
        )
    except (EdgeSwitchError, paramiko.SSHException, socket.error, OSError) as e:
        print(f"ERROR: deploy to {args.switch_host} failed: {e}", file=sys.stderr)
        print(
            f"Leaving {primary_name}, {chain_name} on "
            f"{args.tftp_push_host}:{args.tftp_dir} for troubleshooting.",
            file=sys.stderr,
        )
        sys.exit(1)

    if not args.keep_remote_files:
        ssh_remove([primary_name, chain_name], push_target, args.debug)

    if not args.quiet:
        print("All done!")


if __name__ == "__main__":
    main()
